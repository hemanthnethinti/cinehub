/// CineHub spacing scale.
///
/// Based on a 4-point grid system.
/// Use only these values for padding, margin, gap, and SizedBox dimensions.
/// Never use raw numeric literals for spacing anywhere else.
abstract final class AppSpacing {
  /// 2px
  static const double xxs = 2;
  /// 4px
  static const double xs = 4;
  /// 8px
  static const double sm = 8;
  /// 12px
  static const double md = 12;
  /// 16px
  static const double lg = 16;
  /// 20px
  static const double xl = 20;
  /// 24px
  static const double xxl = 24;
  /// 32px
  static const double huge = 32;
  /// 40px
  static const double massive = 40;
  /// 56px
  static const double colossal = 56;
  /// 80px
  static const double epic = 80;
}
